  /* USER CODE BEGIN 2 */
  HAL_GPIO_WritePin(led_GPIO_Port, led_Pin, GPIO_PIN_SET);  //LED apagado al iniciar (led_estado = 0)
  //el usart1 va al DT-06, no mandar texto de depuracion por ahi
  MQTT_Init();                     //inicia recepcion DMA del MQTT_UARTRX
  HAL_Delay(3000);                 //tiempo para que el DT-06 se conecte a thingsboard
  MQTT_Connect();                  //si falla, MQTT_Loop reintenta cada 5 s
  MQTT_Subscribe(TB_RPC_REQUEST);  //recibir comandos RPC desde thingsboard
