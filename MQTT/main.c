    ADC_Read_All(&hadc1, adc1_canales, adc1_codigo);
    voltaje = (float)adc1_codigo[0] * 3.3 / 4095.0;
    bateria = (float)adc1_codigo[1] * 3.3 / 4095.0;
    bateria = bateria * 4;
  
    MQTT_Loop();  // procesa lo recibido, ping y reconexion

    //cada 5 s manda voltaje como temperatura y bateria como humedad
    if ((HAL_GetTick() - t_envio) >= 500)
    {
      t_envio = HAL_GetTick();
      sprintf( MQTT_TX_BUFF, "{\"temperatura\":%.2f,\"humedad\":%.2f}", voltaje, bateria);
      MQTT_Telemetria( MQTT_TX_BUFF);
    }

    //RPC desde thingsboard: cada linea atiende get<nombre> y set<nombre>
    led_estado   = MQTT_RPC_Bool("LedStatus", led_estado);   //switch: getLedStatus / setLedStatus
    servo_angulo = MQTT_RPC_Float("ServoAngle", servo_angulo);  //slider: getServoAngle / setServoAngle

    //PC13 en la Black Pill enciende con 0 (activo en bajo)
